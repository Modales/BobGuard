SUBSYSTEMS: List[Dict[str, str]] = [
    {"module": "main.py", "role": "FastAPI front door; HTTP <-> event bus; JWT-secured master route; SSE streaming"},
    {"module": "master_event_bus.py", "role": "asyncio.Queue pub/sub router; fan-out, backpressure, race-free drain"},
    {"module": "vector_cve_db.py", "role": "In-memory CVE vector DB; sentence-transformers/FAISS with hashing fallback"},
    {"module": "multi_agent_consensus.py", "role": "3-persona debate; weighted consensus + security veto"},
    {"module": "ast_mutation_engine.py", "role": "AST gate: dangerous-builtin blocklist + loop-depth Big-O guard"},
    {"module": "self_healing_loop.py", "role": "Sandbox retry loop; traceback parsing; exponential backoff"},
    {"module": "roi_calculator.py", "role": "Hours / dollars / CO2e business-value model; auditable assumptions"},
    {"module": "observability_exporter.py", "role": "Prometheus Counter/Histogram/Gauge + /metrics scrape endpoint"},
    {"module": "cross_language_parser.py", "role": "Polyglot scanning: Python AST + JS/TS/Java security rules"},
    {"module": "enterprise_auth.py", "role": "OAuth2 password grant + HS256 JWT (jose or stdlib HMAC)"},
    {"module": "chaos_monkey_tester.py", "role": "Fault-injection suite proving graceful degradation"},
]


# ---------------------------------------------------------------------------
# Document assembly
# ---------------------------------------------------------------------------

def generate_markdown() -> str:
    """Compile the full ARCHITECTURE.md content."""
    routes = collect_routes()
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    route_rows = "\n".join(
        f"| `{r['path']}` | {r['methods']} | {r['auth']} | `{r['response']}` |"
        for r in routes
    )

    schema_sections = "\n".join(
        f"### {group}\n\n" + "\n".join(render_schema_table(m) for m in models)
        for group, models in SCHEMA_REGISTRY.items()
    )

    subsystem_rows = "\n".join(f"| `{s['module']}` | {s['role']} |" for s in SUBSYSTEMS)

    return f"""{GENERATED_BANNER}

# Architecture — Automated Enterprise Legacy & Security Modernizer

*Generated {now} by `auto_doc_generator.py` from live code introspection.*

## System overview

{render_pipeline_flowchart()}

## Multi-agent consensus loop

Every IBM Bob patch must survive a weighted debate before it can ship. The
Security Expert holds a veto that no average can overrule.

{render_consensus_diagram()}

## Event bus topics (pipeline lifecycle)

| # | Topic | Meaning |
| --- | --- | --- |
{chr(10).join(f"| {i} | `{t.name}` (`{t.value}`) | stage of the modernization pipeline |" for i, t in enumerate(Topic))}

## API surface (read live from `main.app`)

| Path | Methods | Auth | Response model |
| --- | --- | --- | --- |
{route_rows}

## Subsystem registry

| Module | Responsibility |
| --- | --- |
{subsystem_rows}

## Data schemas (read live from Pydantic models)

{schema_sections}
## Resilience

See `chaos_monkey_tester.py` — four fault-injection scenarios (Bob timeout,
AST parser crash, sandbox OOM, transport-level 500 contract) all prove the
orchestrator degrades gracefully and never hangs.
"""


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main_cli() -> int:
    parser = argparse.ArgumentParser(description="Generate ARCHITECTURE.md from live code.")
    parser.add_argument("--output", default=str(DEFAULT_OUTPUT), help="output path (default: repo root)")
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is stale")
    args = parser.parse_args()

    content = generate_markdown()
    out = Path(args.output)

    if args.check:
        if not out.exists():
            print(f"STALE: {out} does not exist")
            return 1
        # Ignore the timestamp line when diffing.
        strip_ts = lambda t: "\n".join(  # noqa: E731
            line for line in t.splitlines() if not line.startswith("*Generated ")
        )
        if strip_ts(out.read_text()) != strip_ts(content):
            print(f"STALE: {out} is out of date — run auto_doc_generator.py")
            return 1
        print(f"FRESH: {out} is up to date")
        return 0

    out.write_text(content, encoding="utf-8")
    print(f"Wrote {out} ({len(content)} bytes, {len(collect_routes())} routes, "
          f"{sum(len(m) for m in SCHEMA_REGISTRY.values())} schemas)")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main_cli())
