"""
auto_doc_generator.py — Mermaid & OpenAPI Compiler
==================================================

IBM Bob 2.0 Hackathon · /services/orchestrator/

Zero-effort professional documentation: this script introspects the running
FastAPI application and its Pydantic schemas, then compiles a polished
``ARCHITECTURE.md`` at the repository root — including Mermaid.js diagrams
that GitHub renders natively.

What it generates
-----------------
1. **System overview Mermaid flowchart** — derived from the event-bus topic
   lifecycle (``Topic`` enum), so the diagram can never drift from the code.
2. **Multi-agent consensus loop diagram** — the debate/veto flow.
3. **API route table** — every FastAPI route, method, auth requirement and
   response model, read live from ``main.app``.
4. **Pydantic schema tables** — every request/response/domain model with
   field names, types and required markers, read live from the model classes.
5. **Subsystem registry** — module inventory with one-line responsibilities.

Usage
-----
    python auto_doc_generator.py                 # writes ../ARCHITECTURE.md
    python auto_doc_generator.py --check         # exit 1 if ARCHITECTURE.md is stale (CI gate)

Run it after any route or schema change; wire ``--check`` into CI so the docs
can never silently rot.
"""

from __future__ import annotations

import argparse
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Type

sys.path.insert(0, str(Path(__file__).resolve().parent))

from pydantic import BaseModel  # noqa: E402

import main  # noqa: E402  — the live FastAPI app under documentation
from master_event_bus import Topic  # noqa: E402
from multi_agent_consensus import PERSONAS  # noqa: E402
from vector_cve_db import CVEItem, CVEQueryResult  # noqa: E402
from self_healing_loop import HealAttempt, HealResult, SandboxResult, TracebackInfo  # noqa: E402
from roi_calculator import ROIBreakdownItem, ROISummary  # noqa: E402
from cross_language_parser import PolyglotFinding  # noqa: E402
from enterprise_auth import EnterpriseUser, TokenResponse  # noqa: E402

# ---------------------------------------------------------------------------
# Output location: repo root (one level above services/orchestrator/)
# ---------------------------------------------------------------------------

DEFAULT_OUTPUT = Path(__file__).resolve().parents[2] / "ARCHITECTURE.md"

GENERATED_BANNER = (
    "<!-- GENERATED BY services/orchestrator/auto_doc_generator.py — "
    "DO NOT EDIT BY HAND. Regenerate: python auto_doc_generator.py -->"
)


# ---------------------------------------------------------------------------
# Route introspection
# ---------------------------------------------------------------------------

#: Routes that require a JWT (annotated by hand — auth is enforced via
#: Depends(), which is not visible in the route signature cheaply).
_PROTECTED_PATHS = {"/api/v1/modernize"}


def collect_routes() -> List[Dict[str, str]]:
    """Read every registered route from the live FastAPI app."""
    rows: List[Dict[str, str]] = []
    for route in main.app.routes:
        path = getattr(route, "path", None)
        methods = getattr(route, "methods", None)
        if not path or not methods:
            continue  # mounts / websocket internals
        response_model = getattr(route, "response_model", None)
        rows.append({
            "path": path,
            "methods": ", ".join(sorted(m for m in methods if m != "HEAD")),
            "name": getattr(route, "name", ""),
            "auth": "🔒 JWT (`modernizer` role)" if path in _PROTECTED_PATHS else "public",
            "response": response_model.__name__ if response_model else "—",
            "summary": (getattr(route, "summary", None) or "").strip(),
        })
    rows.sort(key=lambda r: r["path"])
    return rows


# ---------------------------------------------------------------------------
# Schema introspection
# ---------------------------------------------------------------------------

#: Models documented in the generated file, grouped by owning subsystem.
SCHEMA_REGISTRY: Dict[str, List[Type[BaseModel]]] = {
    "Orchestrator API (main.py)": [
        main.ModernizationRequest, main.VulnerabilityItem,
        main.RefactorResult, main.ModernizationResponse,
    ],
    "RAG Security Engine (vector_cve_db.py)": [CVEItem, CVEQueryResult],
    "Self-Healing Engine (self_healing_loop.py)": [SandboxResult, TracebackInfo, HealAttempt, HealResult],
    "Business Value Engine (roi_calculator.py)": [ROIBreakdownItem, ROISummary],
    "Polyglot Parser (cross_language_parser.py)": [PolyglotFinding],
    "Zero-Trust Auth (enterprise_auth.py)": [TokenResponse, EnterpriseUser],
}


def _field_type_str(field: Any) -> str:
    """Render a pydantic field's annotation compactly (``str``, not ``<class 'str'>``)."""
    annotation = getattr(field, "annotation", None)
    if isinstance(annotation, type):
        return annotation.__name__
    text = str(annotation).replace("typing.", "")
    # Drop module prefixes from class references inside generics.
    text = re.sub(r"<class '([\w\.]+)'>", lambda m: m.group(1).split(".")[-1], text)
    text = re.sub(r"<enum '([\w\.]+)'>", lambda m: m.group(1).split(".")[-1], text)
    for module in ("main.", "vector_cve_db.", "self_healing_loop.", "roi_calculator."):
        text = text.replace(module, "")
    return text.replace("NoneType", "None")


def render_schema_table(model: Type[BaseModel]) -> str:
    """Render one model as a Markdown field table."""
    lines = [f"#### `{model.__name__}`", "", "| Field | Type | Required |", "| --- | --- | --- |"]
    for name, field in model.model_fields.items():
        required = "yes" if field.is_required() else "no"
        lines.append(f"| `{name}` | `{_field_type_str(field)}` | {required} |")
    lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Mermaid diagrams (derived from live code where possible)
# ---------------------------------------------------------------------------

def render_pipeline_flowchart() -> str:
    """
    System overview flowchart. The stage chain is derived from the event-bus
    ``Topic`` enum ordering, so adding a topic updates the diagram.
    """
    stages = [t.value for t in Topic]  # declared order == pipeline lifecycle
    stage_nodes = "\n".join(f'    E{i}["{s}"]' for i, s in enumerate(stages))
    stage_edges = "\n".join(f"    E{i} --> E{i + 1}" for i in range(len(stages) - 1))
    return f"""```mermaid
flowchart LR
    subgraph Client["Client"]
        FE["Frontend / demo.sh"]
    end
    subgraph ORCH["Orchestrator (FastAPI, JWT-secured)"]
        API["/api/v1/modernize"]
        BUS["master_event_bus<br/>asyncio.Queue pub/sub"]
        subgraph EVENTS["Pipeline topics (from Topic enum)"]
{stage_nodes}
{stage_edges}
        end
    end
    subgraph EXT["External / mock-fallback services"]
        AUD["Auditor :8001<br/>taint + churn"]
        CVE["vector_cve_db<br/>FAISS / hashing RAG"]
        BOB["IBM Bob agent<br/>CLI or simulation"]
        SBX["Sandbox :8002<br/>test runner"]
    end
    FE -->|"POST + Bearer JWT"| API
    API --> BUS
    BUS --> AUD
    BUS --> CVE
    BUS --> BOB
    BUS --> SBX
    AUD -->|"findings"| BUS
    BOB -->|"patch"| AST["ast_mutation_engine<br/>safety + Big-O gate"]
    AST -->|"gated patch"| BUS
```"""


def render_consensus_diagram() -> str:
    """Multi-agent debate diagram, driven by the live PERSONAS registry."""
    persona_nodes = "\n".join(
        f'    P{i}["{p.name.value}<br/>weight {p.weight}"]' for i, p in enumerate(PERSONAS)
    )
    persona_edges = "\n".join(f"    PATCH --> P{i}\n    P{i} --> SCORE" for i in range(len(PERSONAS)))
    return f"""```mermaid
flowchart TD
    PATCH["IBM Bob refactored patch"] 
{persona_nodes}
    SCORE["calculate_consensus<br/>weighted mean"]
    VETO{{"security score<br/>>= veto threshold?"}}
    APPROVE["CONSENSUS_REACHED<br/>approved=true"]
    REJECT["rejected_consensus<br/>patch discarded"]
{persona_edges}
    SCORE --> VETO
    VETO -->|"yes + score >= 0.70"| APPROVE
    VETO -->|"no"| REJECT
    APPROVE --> HEAL["self_healing_loop<br/>sandbox retries x5"]
    HEAL -->|"passed"| DONE["TESTS_PASSED"]
    HEAL -->|"exhausted"| FAIL["TESTS_FAILED"]
```"""


# ---------------------------------------------------------------------------
